"""Prepare a shared event without authenticating to any hosted service.

The generated SQL validates the director and optional approver's confirmed
email/password identities in Supabase. Payment approvals follow the director-configured event policy.
A protected local plan keeps IDs stable if the owner reruns this command.
"""

from __future__ import annotations

import json
import os
import re
import tempfile
from pathlib import Path
from uuid import UUID, uuid4


def _literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def event_sql(
    *,
    name: str,
    director_user_id: str,
    currency: str,
    plan_path: Path,
    approver_user_id: str | None = None,
) -> str:
    director = str(UUID(director_user_id))
    approver = str(UUID(approver_user_id)) if approver_user_id is not None else None
    if director == approver:
        raise ValueError("Two distinct actual confirmed email/password users are required")
    name, currency = name.strip(), currency.upper()
    if not name or len(name) > 100 or not re.fullmatch(r"[A-Z0-9]{3,12}", currency):
        raise ValueError("Event name or currency is invalid")
    expected = {
        "name": name,
        "currency": currency,
        "director_user_id": director,
        "approver_user_id": approver,
    }
    if plan_path.exists():
        plan = json.loads(plan_path.read_text())
        if any(plan.get(key) != value for key, value in expected.items()):
            raise ValueError("Existing event plan differs; use a separate explicit plan path")
        org, run = str(UUID(plan["organization_id"])), str(UUID(plan["run_id"]))
    else:
        org, run = str(uuid4()), str(uuid4())
        plan_path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        with tempfile.NamedTemporaryFile(
            mode="w", dir=plan_path.parent, prefix="event-plan-", delete=False
        ) as handle:
            temporary = Path(handle.name)
            os.chmod(temporary, 0o600)
            json.dump({**expected, "organization_id": org, "run_id": run}, handle, indent=2)
        temporary.replace(plan_path)
    return f"""-- Generated by finance event-sql. No network connection was made.
-- Run once in the event owner's Supabase SQL editor after migrations.
-- Repeat this exact SQL safely; it will not promote an unrelated existing member.
-- {"No separate approver configured; director selects the event payment approval policy." if approver is None else "A distinct approver is configured; payment approval requirements are unchanged."}
begin;
do $finance_setup$
declare
  org uuid := '{org}';
  event_run uuid := '{run}';
  director uuid := '{director}';
  approver uuid := {_literal(approver) if approver is not None else "null"};
begin
  if director = approver then raise exception 'Two distinct people are required'; end if;
  if not exists(
    select 1 from auth.users u join auth.identities i on i.user_id=u.id
    where u.id=director and i.provider='email' and u.is_anonymous is false
      and nullif(btrim(u.email),'') is not null and u.email_confirmed_at is not null
      and nullif(u.encrypted_password,'') is not null
  ) then
    raise exception 'Director needs an existing confirmed non-anonymous Supabase email/password account';
  end if;
  if approver is not null and not exists(
    select 1 from auth.users u join auth.identities i on i.user_id=u.id
    where u.id=approver and i.provider='email' and u.is_anonymous is false
      and nullif(btrim(u.email),'') is not null and u.email_confirmed_at is not null
      and nullif(u.encrypted_password,'') is not null
  ) then
    raise exception 'Approver needs an existing confirmed non-anonymous Supabase email/password account';
  end if;
  insert into public.organizations(id,name) values(org,{_literal(name)}) on conflict(id) do nothing;
  if not exists(select 1 from public.organizations where id=org and name={_literal(name)}) then
    raise exception 'Existing organization does not match this setup plan'; end if;
  insert into public.memberships(organization_id,user_id,role,active)
    values(org,director,'director',true) on conflict(organization_id,user_id) do nothing;
  if approver is not null then
    insert into public.memberships(organization_id,user_id,role,active)
      values(org,approver,'approver',true) on conflict(organization_id,user_id) do nothing;
  end if;
  if not exists(select 1 from public.memberships where organization_id=org and user_id=director and role='director' and active)
     or (approver is not null and not exists(select 1 from public.memberships where organization_id=org and user_id=approver and role='approver' and active)) then
    raise exception 'Existing memberships differ; review them explicitly'; end if;
  insert into public.demo_runs(id,organization_id,name,currency,owner_user_id,is_demo)
    values(event_run,org,{_literal(name + " finances")},{_literal(currency)},director,false) on conflict(id) do nothing;
  if not exists(select 1 from public.demo_runs where id=event_run and organization_id=org and owner_user_id=director and not is_demo and status='active' and currency={_literal(currency)}) then
    raise exception 'Existing event run does not match this setup plan'; end if;
end $finance_setup$;
select '{org}' as organization_id, '{run}' as run_id,
  {"false" if approver is None else "true"} as approver_configured;
commit;
"""
